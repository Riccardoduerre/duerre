export function getPreferredLocale(): Locale {
  try {
    const urlLocale = new URLSearchParams(window.location.search).get('lang');
    if (urlLocale === 'en' || urlLocale === 'it') return urlLocale;
  } catch {
    // Ignore unavailable browser URL APIs and use stored/browser preferences.
  }

  try {
    const stored = localStorage.getItem('lang');
    if (stored === 'en' || stored === 'it') return stored;
  } catch {
    // Ignore storage access issues and fall back to safe browser defaults.
  }

  try {
    const nav = typeof navigator !== 'undefined' ? navigator.language || navigator.languages?.[0] : '';
    if (nav) {
      const navigatorLang = nav.toLowerCase();
      if (navigatorLang.startsWith('it')) return 'it';
      if (navigatorLang.startsWith('en')) return 'en';
    }
  } catch {
    // Ignore environment or browser API issues and default to Italian.
  }

  return 'it';
}

export function getTranslation(key: string, locale: Locale) {
  return translations[locale]?.[key] ?? translations.en[key] ?? key;
}
